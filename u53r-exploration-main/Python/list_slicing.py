




#Support negative indexing
#Negative indexing means start from the end of the list.
#list[start:stop:step]

#start → saan magsisimula
#stop → saan titigil (exclusive)
#step → direction at lundag

#   +1 (default) = left to right
#   -1 = right to left





fruit = ['apple',
         'banana',
         'cherry',
         'kiwi',
         'mango',
         'orange',
         'grape',
         'peach',]

#slicing [start:stop:step]
# start = 0, stop = 5, step = 2
print(fruit[0:5:2])



