

#include <iostream>

int main() {

    // First pair of lines using std::endl
    std::cout << "This is the first line using std::endl." << std::endl;
    std::cout << "This is the second line using std::endl." << std::endl;

    // Second pair of lines using \n
    std::cout << "This is the first line using \\n.\n";
    std::cout << "This is the second line using \\n.\n";

    return 0;
}
