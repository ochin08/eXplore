
// Control Flow in JavaScript


//  1. if-else (pagdedesisyon)
let age = 18;

if (age >= 18) {
  console.log("Adult");
} else {
  console.log("Minor");
}


// 2. for loop (paulit-ulit)
for (let i = 0; i < 3; i++) {
    console.log(i);
  }

  
// 3. switch (maraming choice)
let color = "red";

switch(color) {
  case "red":
    console.log("Stop");
    break;
  case "green":
    console.log("Go");
    break;
  default:
    console.log("Unknown color");
}


